import math

a = 10
b = 4

print("Addition:", a + b)
print("Subtraction:", a - b)
print("Multiplication:", a * b)
print("Division:", a / b)
print("Floor Division:", a // b)
print("Modulus:", a % b)
print("Exponentiation:", a ** b)

# math library functions
print("Square root of a:", math.sqrt(a))
print("Power of a to b:", math.pow(a, b))